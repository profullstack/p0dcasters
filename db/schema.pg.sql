-- Search. The FTS5 index (title, description, author, host; bm25 weights
-- 8/1/3/4) becomes a weighted tsvector: A = title, B = host, C = author,
-- D = description, so ts_rank orders results the way bm25 did. It is an
-- expression index rather than a stored column so `SELECT *` over `podcasts`
-- keeps returning the row the app expects and nothing else; the reload only
-- has to recreate the index. The `simple` configuration tokenises without
-- stemming, like FTS5's unicode61 did, so prefix matches (`term:*`) behave.
create or replace function p0d_search_vector(title text, host text, author text, description text)
  returns tsvector
  language sql immutable parallel safe
as $$
  select setweight(to_tsvector('simple', coalesce(title, '')), 'A')
      || setweight(to_tsvector('simple', coalesce(host, '')), 'B')
      || setweight(to_tsvector('simple', coalesce(author, '')), 'C')
      || setweight(to_tsvector('simple', coalesce(description, '')), 'D')
$$;

create unique index if not exists i_slug on podcasts(slug);
create index if not exists i_cat on podcasts(category);
create index if not exists i_lang on podcasts(lang_base);
create index if not exists i_host on podcasts(host);
create index if not exists i_score on podcasts(score desc);
create index if not exists i_new on podcasts(newest_pubdate desc);
create index if not exists i_search on podcasts using gin (p0d_search_vector(title, host, author, description));
